/**
 * 剖面页「怎么看」说明文案（摄影师视角）。
 *
 * 定位：纯文案数据，不参与任何计算，不碰 scoreOf()、不读 forecast 缓存。
 * 为什么单独一个文件：
 *   · 这些解释要跟按钮保持一对一，放在页面里会散成几十个 title，改一个漏一个；
 *   · 文案可能被别处（关于页/帮助）复用；
 *   · 独立文件能被 tools/test-guide.mjs 静态检查「每个按钮都有解释」。
 *
 * 写作口径（重要，不要改成营销腔）：
 *   · 只讲「这个按钮改变什么、你在图上会看到什么、对拍摄意味着什么」；
 *   · 不确定的地方写「看不出/仅作参考」，不编造物理意义；
 *   · 一直强调：这是模式云的「哪一层可能有云」，不是雷达/卫星实测。
 */

/** 一条说明：控制项名 + 一句话作用 + 拍摄上怎么用 + （可选）别误读 */
export interface GuideItem {
  /** 对应工具条上的分组名或按钮名（用于人工对照，不参与渲染匹配） */
  name: string
  /** 它到底改变什么 */
  what: string
  /** 摄影师怎么用 */
  use: string
  /** 常见误读（可选） */
  caution?: string
}

export interface GuideGroup {
  /** 分组标题 */
  title: string
  /** 分组一句话总述 */
  lead: string
  items: GuideItem[]
}

