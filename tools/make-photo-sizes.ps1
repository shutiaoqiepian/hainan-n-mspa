# Generate src/data/photo-sizes.ts -- real pixel size of every photo.
#
# Why: the wall uses <img width:100%; height:auto>. Before the file loads the
# browser does not know the height, so everything below jumps once it arrives
# (measured CLS 0.26 on the home page). Width/height attributes reserve the
# space up front, so loading a photo no longer moves the layout.
#
# When to run: after adding/replacing photos in images/, or after editing photos.ts.
#   powershell -ExecutionPolicy Bypass -File tools/make-photo-sizes.ps1

param([string]$Root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path)

Add-Type -AssemblyName System.Drawing

$thumbDir = Join-Path $Root 'images\thumbs'
$fullDir = Join-Path $Root 'images'
$out = Join-Path $Root 'src\data\photo-sizes.ts'

if (-not (Test-Path $thumbDir)) {
  Write-Host 'images\thumbs not found - run 3-ya-su-xin-tu-pian.bat first.' -ForegroundColor Red
  exit 1
}

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('/* AUTO-GENERATED by tools/make-photo-sizes.ps1 - do not edit by hand.')
$lines.Add(' * Pixel size of each photo. Used as <img width height> so the browser')
$lines.Add(' * reserves space before the image loads (removes layout shift). */')
$lines.Add('')
$lines.Add('export interface PhotoSize {')
$lines.Add('  w: number')
$lines.Add('  h: number')
$lines.Add('}')
$lines.Add('')
$lines.Add('export const PHOTO_SIZES: Readonly<Record<string, PhotoSize>> = {')

$count = 0
Get-ChildItem -Path $fullDir -File |
  Where-Object { $_.DirectoryName -eq $fullDir -and $_.Extension -match '^\.(jpg|jpeg|png|webp)$' } |
  Sort-Object Name |
  ForEach-Object {
    $name = $_.Name
    $thumb = Join-Path $thumbDir $name
    $target = if (Test-Path $thumb) { $thumb } else { $_.FullName }
    try {
      $img = [System.Drawing.Image]::FromFile($target)
      $w = $img.Width
      $h = $img.Height
      $img.Dispose()
      $safe = $name.Replace('\', '\\').Replace("'", "\'")
      $lines.Add("  '$safe': { w: $w, h: $h },")
      $count++
    } catch {
      Write-Host "skip (unreadable): $name" -ForegroundColor Yellow
    }
  }

$lines.Add('}')
$lines.Add('')

$utf8Bom = New-Object System.Text.UTF8Encoding($true)
[System.IO.File]::WriteAllLines($out, $lines, $utf8Bom)

Write-Host ("wrote {0} entries -> {1}" -f $count, $out) -ForegroundColor Green
